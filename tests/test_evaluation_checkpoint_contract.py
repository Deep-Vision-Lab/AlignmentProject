def test_explicit_pairs_cannot_bypass_source_page_split(native_dataset, tmp_path):
    from Evaluation.sw_core import ImagePair
    from Evaluation.sw_dataset import select_source_page_pairs
    root, images = native_dataset
    pairs = [ImagePair(i, image, image) for i, image in enumerate(images)]
    selected, metadata = select_source_page_pairs(
        pairs, root, text_key="text_original_path", seed=42, split="test")
    assert len(selected) == 2 and all(p.split == "test" for p in selected)
    assert metadata["source_page_counts"] == {"train": 6, "valid": 2, "test": 2}
    alien = tmp_path / "unknown_page/linesImages/line_01.png"
    alien.parent.mkdir(parents=True)
    Image.new("L", (50, 20)).save(alien)
    with pytest.raises(ValueError, match="source-page identity"):
        select_source_page_pairs([ImagePair(0, alien, alien)], root,
                                 text_key="text_original_path", seed=42, split="test")



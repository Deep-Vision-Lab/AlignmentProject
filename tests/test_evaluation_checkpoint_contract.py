@pytest.mark.parametrize("channels,mean,std", [
    (1, (0.449,), (0.226,)),
    (3, (0.485, 0.456, 0.406), (0.229, 0.224, 0.225)),
])
def test_prepared_pixels_only_tensorization(channels, mean, std):
    config = dict(GRAY_CONFIG) if channels == 1 else {
        "visual_input_channels": 3, "visual_grayscale": False,
        "line_geometry_mode": "crop-aspect-preserving-rgb", "real_binarize": False}
    contract = resolve_evaluation_contract(config)
    image = Image.new("L" if channels == 1 else "RGB", (67, 29), 173 if channels == 1 else (173, 111, 57))
    tensor = build_transform(contract=contract, prepared=True)(image)
    assert tensor.shape == (channels, 29, 67)  # no second resize/crop/pad
    assert contract.normalization_mean == mean
    assert contract.normalization_std == std
    pixels = torch.tensor([173] if channels == 1 else [173, 111, 57], dtype=torch.float32) / 255
    expected = (pixels - torch.tensor(mean)) / torch.tensor(std)
    assert torch.equal(tensor[:, 0, 0], expected)
    assert image.mode == ("L" if channels == 1 else "RGB")



@pytest.mark.parametrize("index", [0, 3, 9])
def test_training_point2_quantitative_and_point6_are_exact(native_dataset, gray_models, monkeypatch, tmp_path, index):
    root, images = native_dataset
    with evaluation_environment(TRAIN_ENV):
        from unified_line_geometry import install_training_geometry
        install_training_geometry()
        dataset = ArabicAllPageLinesDataset(root, transform=build_tensor_transform("real", False), validate_paths=True)
        _text, cropped = dataset.read_prepared_pil(index)
        reference = build_preprocessor("real", False)(cropped)
        reference_tensor = dataset[index][1]
    # Deliberately hostile inherited geometry, including an import that exports P.
    monkeypatch.setenv("REAL_BBOX_CROP", "0")
    monkeypatch.setenv("REAL_BINARIZE", "1")
    monkeypatch.setenv("VISUAL_GRAYSCALE", "0")
    monkeypatch.setenv("ZERO_SHOT_PRESERVE_ASPECT", "1")
    monkeypatch.setenv("PACK_VALID_WINDOWS", "1")
    monkeypatch.setenv("FULL_IMAGE_NO_PADDING", "0")
    prepared, _ = prepare_line(images[index], "real", "training", contract=gray_models.contract)
    assert prepared.mode == "L" and prepared.size == (1024, 128)
    assert np.array_equal(np.asarray(reference), np.asarray(prepared))
    assert torch.equal(reference_tensor, gray_models.contract.tensor_transform()(prepared))
    saved = tmp_path / "prepared.png"
    prepared.save(saved)
    observed = []
    original = gray_models.image_model.vit_encoder.encode_restoration_sequence

    def capture(tensor, **kwargs):
        observed.append(tensor.detach().cpu())
        return original(tensor, **kwargs)

    monkeypatch.setattr(gray_models.image_model.vit_encoder, "encode_restoration_sequence", capture)
    point2_features = _encode_line(gray_models, saved, "fused", side=1)
    qroot = tmp_path / "quantitative"
    qroot.mkdir()
    runtime = quantitative_real._install_runtime()
    qfeatures = quantitative_real._feature_cache(runtime, gray_models, "real", qroot)(images[index])
    with Image.open(qroot / "real_000000.png") as qim:
        assert qim.mode == "L"
        assert np.array_equal(np.asarray(qim), np.asarray(reference))
    pair = pair_loader.Pair(1, images[index], images[index], "real", "real", "real",
                            side1_preprocess="real", side2_preprocess="real")
    point6_lines = point6._build_lines(gray_models, [pair], "training")
    point3_training._extract_training_bundle(gray_models, saved)
    get_image_features(gray_models, images[index], "real")
    assert len(observed) == 5
    assert all(t.shape == (1, 1, 128, 1024) and torch.equal(t[0], reference_tensor) for t in observed)
    assert point2_features.ink.bool().sum() == 63
    assert point6_lines[0].valid.sum() == 63
    assert point6_lines[0].seq_to_physical == list(range(62, -1, -1))
    assert torch.equal(point6_lines[0].fused, point2_features.contextual.cpu())
    torch.testing.assert_close(qfeatures.contextual, point2_features.contextual, rtol=0, atol=3e-8)


def test_source_page_split_matches_training_and_pair_eligibility(native_dataset, monkeypatch):
    root, images = native_dataset
    mapping, dataset = _all_page_line_split_map(root, text_key="text_original_path", seed=42)
    import DataLoader
    monkeypatch.setattr(DataLoader, "_split_seed", 42)
    training_splits = DataLoader._group_split_real_dataset(dataset)
    page_sets = {}
    for name, subset in zip(("train", "valid", "test"), training_splits):
        page_sets[name] = {dataset.samples[i]["pair_id"] for i in subset.indices}
        assert page_sets[name] == {page for page, split in mapping.items() if split == name}
    assert all(page_sets[a].isdisjoint(page_sets[b]) for a, b in (("train", "valid"), ("train", "test"), ("valid", "test")))
    monkeypatch.setenv("REAL_ALL_PAGE_LINES", "0")
    args = SimpleNamespace(data_dir=str(root), arabic_manifest=None, real_text_key="text_original_path",
        real_labels="high_match", real_min_text_score=0., real_validate_paths=True, split_seed=42, real_split="test")
    selected = load_arabic_dataset_pairs(args, checkpoint_config=GRAY_CONFIG)
    assert len(selected) == 2
    assert all(p.split == "test" for p in selected)
    from Evaluation.sw_dataset import _page_key_for_real_line
    assert all(_page_key_for_real_line(path, dataset) in page_sets["test"] for p in selected for path in (p.image1, p.image2))
    # A pair straddling training/test must never be relabeled as test.
    records = [json.loads(line) for line in (root / "dataset_manifest.jsonl").read_text().splitlines()]
    train_image = next(im for im in images if _page_key_for_real_line(im, dataset) in page_sets["train"])
    mixed = dict(records[0], pair_id="mixed",
                 A={"line_image_path": str(selected[0].image1), "text_original_path": str(selected[0].text1)},
                 B={"line_image_path": str(train_image), "text_original_path": str(train_image.parent.parent / "text/final/original/line_01.txt")})
    (root / "dataset_manifest.jsonl").write_text("\n".join(json.dumps(r) for r in records + [mixed]))
    assert all(p.pair_id != "mixed" for p in load_arabic_dataset_pairs(args, checkpoint_config=GRAY_CONFIG))
    args.split_seed = 43
    with pytest.raises(ValueError, match="split seed"):
        load_arabic_dataset_pairs(args, checkpoint_config=GRAY_CONFIG)



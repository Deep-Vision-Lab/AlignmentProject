def test_mask_flags_belong_to_model_even_after_ambient_changes(gray_models, monkeypatch):
    x = torch.full((1, 1, 128, 1024), (1 - 0.449) / 0.226)
    x[:, :, :, 400:624] = -0.449 / 0.226
    outputs = []
    for pack, full in (("0", "1"), ("0", "0"), ("1", "1"), ("1", "0")):
        monkeypatch.setenv("PACK_VALID_WINDOWS", pack)
        monkeypatch.setenv("FULL_IMAGE_NO_PADDING", full)
        with torch.inference_mode():
            bundle = gray_models.image_model(x, return_training_bundle=True)
        assert bundle["token_valid"].shape == (1, 63)
        assert bool(bundle["token_valid"].all())
        outputs.append(bundle["semantic"])
        assert os.environ["PACK_VALID_WINDOWS"] == pack
        assert os.environ["FULL_IMAGE_NO_PADDING"] == full
    assert all(torch.equal(outputs[0], out) for out in outputs[1:])



# Partial-overlap generator defaults. Override from the command line for ablations.
export REAL_PARTIAL_OVERLAP_MAX_SHARED_ISLANDS="${REAL_PARTIAL_OVERLAP_MAX_SHARED_ISLANDS:-3}"
